const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'site/assets/page-jump.js'),'utf8'),context);
const books=JSON.parse(fs.readFileSync(path.join(root,'site/data/books.json'),'utf8')).books;
const {entries,filter}=context.window.PageJump,items=entries(books);
const sectionCount=books.reduce((n,b)=>n+b.chapters.reduce((v,ch)=>v+ch.sections.length,0),0);
assert.equal(items.filter(i=>i.kind==='正文').length,sectionCount);
assert.equal(new Set(items.map(i=>i.href)).size,items.length);
assert(items.some(i=>i.href==='#/fanhan/1.1/exercises'));
assert(items.some(i=>i.href==='#/gailv/chapter-5/exercises/topic-density'));
assert(!items.some(i=>i.href==='#/gailv/5.3/exercises'));
assert(filter(items,'概率论 密度').some(i=>i.href==='#/gailv/5.3'));
assert(filter(items,'投影定理').every(i=>`${i.label} ${i.chapter}`.includes('投影定理')));
assert(filter(items,'习题','fanhan').every(i=>i.bookId==='fanhan'&&i.kind==='习题'));
for(const item of items)assert(!('src' in item || 'html' in item),'Jump list must only use titles and metadata');
const html=fs.readFileSync(path.join(root,'site/index.html'),'utf8');
assert(html.indexOf('id="search"')>html.indexOf('<main id="main">'));
assert.equal((html.match(/id="search"/g)||[]).length,1);
console.log(`PASS: ${sectionCount} sections across all books, ${items.length} unique title/exercise links, filtering and one shared main-page search.`);
